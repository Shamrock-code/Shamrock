    /// Unit systems the reference values are given in
    enum class RefSystem { SI, Astro, CGS };

    constexpr RefSystem ref_systems[] = {RefSystem::SI, RefSystem::Astro, RefSystem::CGS};

    const char *ref_system_name(RefSystem s) {
        switch (s) {
        case RefSystem::SI   : return "si";
        case RefSystem::Astro: return "astro";
        case RefSystem::CGS  : return "cgs";
        }
        return "?";
    }

    // Built from literal base units, never from get<>(), so the systems don't depend on the code
    // under test.
    template<class T>
    UnitSystem<T> make_system(RefSystem s) {
        switch (s) {
        case RefSystem::SI: return UnitSystem<T>{};
        case RefSystem::Astro:
            return UnitSystem<T>{3.15576e13, 1.495978707e11, 1.98847e30}; // Myr, au, Msol
        case RefSystem::CGS: return UnitSystem<T>{1, 1e-2, 1e-3};
        }
        return UnitSystem<T>{};
    }

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // Adapters: the only places that know the shamunits API. A migration rewrites these, never the
    // tables.
    ////////////////////////////////////////////////////////////////////////////////////////////////

    /// Runtime path, as used by the Python bindings (UnitSystem.get)
    template<class T>
    T unit_value(UnitSystem<T> &u, const std::string &name, const std::string &pref, int power) {
        return u.get(shamunits::prefix::from_name(pref) * shamunits::units::from_name(name), power);
    }

    /// Constants, as exposed by the Python bindings (Constants(usys).G(power=p))
    template<class T>
    T constant_value(UnitSystem<T> &u, const std::string &name, int power) {
        return Constants<T>{u}.get(shamunits::constants::from_name(name), power);
    }

    /// Template path, as used by the C++ call sites (the map keys keep their original
    /// spelling: they are the ids of the reference rows)
    template<class T>
    const std::unordered_map<std::string, T (*)(UnitSystem<T> &)> template_getters = {
        {"to<kilogram>",
         [](UnitSystem<T> &u) -> T {
             return u.template to<units::kilogram>();
         }},
        {"to<metre>",
         [](UnitSystem<T> &u) -> T {
             return u.template to<units::metre>();
         }},
        {"to<second>",
         [](UnitSystem<T> &u) -> T {
             return u.template to<units::second>();
         }},
        {"Constants::G",
         [](UnitSystem<T> &u) -> T {
             return Constants<T>{u}.template get<shamunits::constants::G>();
         }},
        {"Constants::c",
         [](UnitSystem<T> &u) -> T {
             return Constants<T>{u}.template get<shamunits::constants::c>();
         }},
        {"Constants::mu_0",
         [](UnitSystem<T> &u) -> T {
             return Constants<T>{u}.template get<shamunits::constants::mu_0>();
         }},
        {"get<astronomical_unit, 2>",
         [](UnitSystem<T> &u) -> T {
             return u.template get<upow(units::astronomical_unit, 2)>();
         }},
        {"get<mega, years>",
         [](UnitSystem<T> &u) -> T {
             return u.template get<prefix::mega * units::year>();
         }},
        {"to<mega, years>",
         [](UnitSystem<T> &u) -> T {
             return u.template to<prefix::mega * units::year>();
         }},
        {"get<kilo, Joule>",
         [](UnitSystem<T> &u) -> T {
             return u.template get<prefix::kilo * units::joule>();
         }},
        {"to<kilo, Joule>",
         [](UnitSystem<T> &u) -> T {
             return u.template to<prefix::kilo * units::joule>();
         }},
    };

    template<class T>
    T template_value(UnitSystem<T> &u, const std::string &name) {
        return template_getters<T>.at(name)(u);
    }

