    struct Ref {
        const char *name;
        const char *prefix;
        int power;
        double si, astro, cgs;
    };

    struct ConstantRef {
        const char *name;
        int power;
        double si, astro, cgs;
    };

    struct TemplateRef {
        const char *name;
        double si, astro, cgs;
    };

    template<class R>
    double expected_value(const R &ref, RefSystem s) {
        switch (s) {
        case RefSystem::SI   : return ref.si;
        case RefSystem::Astro: return ref.astro;
        case RefSystem::CGS  : return ref.cgs;
        }
        return nan_v;
    }

    std::string ref_id(const Ref &r) {
        return std::string("unit:") + r.name + " " + r.prefix + " " + std::to_string(r.power);
    }
    std::string ref_id(const ConstantRef &r) {
        return std::string("constant:") + r.name + " " + std::to_string(r.power);
    }
    std::string ref_id(const TemplateRef &r) { return std::string("template:") + r.name; }

