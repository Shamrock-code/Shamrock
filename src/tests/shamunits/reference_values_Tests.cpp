    std::array<std::span<const F32Ref>, 1> f32_ref_tables() {
        return {std::span<const F32Ref>{f32_out_of_range_refs}};
    }

    constexpr double tol_f64 = 1e-13;
    constexpr double tol_f32 = 1e-6;

    const F32Ref *find_f32_ref(const std::string &id, RefSystem s) {
        for (std::span<const F32Ref> tbl : f32_ref_tables()) {
            for (const F32Ref &r : tbl) {
                if (r.system == s && id == r.id) {
                    return &r;
                }
            }
        }
        return nullptr;
    }

    /// Compare as a ratio: values span 1e-121 to 1e89 and REQUIRE_FLOAT_EQUAL is absolute
    void require_close(const std::string &label, double got, double expected, double tol) {
        if (std::isnan(expected)) {
            REQUIRE_NAMED(label, std::isnan(got));
        } else if (std::isinf(expected) || expected == 0) {
            REQUIRE_EQUAL_NAMED(label, got, expected);
        } else {
            REQUIRE_FLOAT_EQUAL_NAMED(label, got / expected, 1.0, tol);
        }
    }

    template<class T>
    void check_value(
        const std::string &id,
        RefSystem s,
        T got,
        double expected,
        std::set<const F32Ref *> &used_f32_refs) {

        std::string label
            = std::string(std::is_same_v<T, f32> ? "f32 " : "f64 ") + ref_system_name(s) + " " + id;

        if constexpr (std::is_same_v<T, f32>) {
            if (const F32Ref *r = find_f32_ref(id, s); r != nullptr) {
                used_f32_refs.insert(r);
                require_close(label, got, r->value, tol_f32);
            } else {
                require_close(label, got, expected, tol_f32);
            }
        } else {
            require_close(label, got, expected, tol_f64);
        }
    }

    template<class T>
    void check_all(std::set<const F32Ref *> &used_f32_refs) {
        for (RefSystem s : ref_systems) {
            UnitSystem<T> u = make_system<T>(s);

            for (const Ref &r : unit_refs) {
                check_value(
                    ref_id(r),
                    s,
                    unit_value(u, r.name, r.prefix, r.power),
                    expected_value(r, s),
                    used_f32_refs);
            }

            for (const ConstantRef &r : constant_refs) {
                check_value(
                    ref_id(r),
                    s,
                    constant_value(u, r.name, r.power),
                    expected_value(r, s),
                    used_f32_refs);
            }

            for (const TemplateRef &r : template_refs) {
                check_value(
                    ref_id(r), s, template_value(u, r.name), expected_value(r, s), used_f32_refs);
            }
        }
    }

